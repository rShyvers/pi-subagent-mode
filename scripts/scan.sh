#!/usr/bin/env bash
# Cleanliness scan for everything that would be committed. Fails on:
#   - common secret patterns
#   - un-substituted template placeholders
#   - agent/AI traces in code or docs
# Patterns are split across string concatenations so this script never matches itself.
set -u
cd "$(dirname "$0")/.."

# Scan exactly what would be committed: tracked files plus untracked, non-ignored ones.
if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  mapfile -t files < <(git ls-files --cached --others --exclude-standard)
else
  mapfile -t files < <(find . -type f -not -path "./node_modules/*" -not -path "./.git/*")
fi

fail=0
check() { # $1=label  $2=extra grep flags  $3=extended regex
  local hits
  # $2 may be empty; ${2:+$2} vanishes entirely so it is never passed as a pattern
  hits=$(printf '%s\n' "${files[@]}" | xargs grep -InE ${2:+$2} "$3" 2>/dev/null || true)
  if [ -n "$hits" ]; then
    echo "FAIL [$1]:"
    echo "$hits"
    fail=1
  else
    echo "PASS [$1]"
  fi
}

check "secrets" "" \
  "ghp_[A-Za-z0-9]{36}|github_pat_[A-Za-z0-9_]{20,}|xox[baprs]-[A-Za-z0-9-]{10,}|AKIA[0-9A-Z]{16}|-----BEGIN [A-Z ]*PRIVATE KEY|sk-ant-[A-Za-z0-9-]{20,}"

check "placeholders" "" \
  "<NPM_""SCOPE>|<AUTHOR_""NAME>|<GH_""USER>|<VISIBI""LITY>"

check "agent-traces" "-i" \
  "co-""authored-by|generated by (cl""aude|co""pilot|an ai)|[Cc]l""aude|[Cc]o""pilot"

echo
if [ "$fail" -ne 0 ]; then
  echo "Cleanliness scan FAILED."
  exit 1
fi
echo "Cleanliness scan passed."
